// Builds the small Japanese font the English pages need: the seal, the vertical lines,
// the station stamps and the Japanese terms. Re-run after changing Japanese text in en.ts.
//
//   1. Download ShipporiMinchoB1-Medium.ttf and -ExtraBold.ttf (OFL) from
//      https://github.com/google/fonts/tree/main/ofl/shipporiminchob1 into .taste-skill/fonts/
//   2. node scripts/subset-jp.mjs   (needs uv, which runs fonttools without installing it)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const sources = ['src/data/en.ts', 'src/components/Seal.astro', 'src/components/Contact.astro'];
const text = sources.map((f) => readFileSync(f, 'utf8')).join('');
const jp = new Set([...text].filter((c) => /[　-ヿ㐀-鿿＀-￯]/u.test(c)));
const chars = [...jp].sort().join('') + 'PoCAPMD';
mkdirSync('.taste-skill', { recursive: true });
writeFileSync('.taste-skill/jp-chars.txt', chars);
console.log(`${jp.size} Japanese characters:`, [...jp].sort().join(''));

for (const [weight, file] of [['500', 'Medium'], ['800', 'ExtraBold']]) {
  execFileSync('uv', [
    'tool', 'run', '--from', 'fonttools[woff]', 'pyftsubset',
    `.taste-skill/fonts/ShipporiMinchoB1-${file}.ttf`,
    '--text-file=.taste-skill/jp-chars.txt',
    '--layout-features=*',
    '--flavor=woff2',
    `--output-file=public/fonts/shippori-mincho-b1-subset-${weight}.woff2`,
  ], { stdio: 'inherit' });
}
// The @font-face rules carry the exact unicode-range, so on Japanese pages the full face
// (loaded by ja-fonts.css) supplies every character the subset doesn't have.
const range = [...new Set(chars)].map((c) => c.codePointAt(0)).sort((a, b) => a - b).map((cp) => `U+${cp.toString(16).toUpperCase()}`).join(',');
const face = (w) => `@font-face {\n  font-family: 'Shippori Mincho B1';\n  font-style: normal;\n  font-weight: ${w};\n  font-display: swap;\n  src: url('/fonts/shippori-mincho-b1-subset-${w}.woff2') format('woff2');\n  unicode-range: ${range};\n}\n`;
writeFileSync('src/styles/jp-subset.css', `/* Generated by scripts/subset-jp.mjs. Do not edit by hand. */\n${face(500)}${face(800)}`);
console.log('Wrote public/fonts/shippori-mincho-b1-subset-{500,800}.woff2 and src/styles/jp-subset.css');
